// Builds supabase/seed.sql from fixtures/synthetic/phase2.json.
// Self-contained (no imports) so Node can run it directly and tests can import it.

interface Fixture {
  version: string;
  notice: string;
  organization: { id: string; name: string };
  branches: Array<{
    id: string;
    code: string;
    name_en: string;
    name_ar: string;
    timezone: string;
    business_day_rollover: string;
    operates_in_app: boolean;
  }>;
  business_days: Array<{
    id: string;
    branch_code: string;
    business_date: string;
    status: string;
    closed_at: string | null;
    net_sales: string | null;
    order_count: number | null;
    card_amount: string | null;
    opening_cash: string | null;
    revision: number;
  }>;
  cash_movements: Array<{
    id: string;
    branch_code: string;
    business_date: string;
    kind: string;
    amount: string;
    occurred_at: string;
    note: string;
  }>;
  cash_counts: Array<{
    id: string;
    branch_code: string;
    business_date: string;
    counted_amount: string;
    counted_at: string;
    expected_cash: string | null;
    variance: string | null;
    calc_version: string;
  }>;
  comparison_figures: Array<{
    id: string;
    branch_code: string;
    business_date: string;
    net_sales: string | null;
    order_count: number | null;
    source: string;
    entered_at: string;
  }>;
}

const text = (value: string | null): string => (value === null ? "null" : `'${value.replaceAll("'", "''")}'`);
const num = (value: string | number | null): string => (value === null ? "null" : String(value));
const bool = (value: boolean): string => (value ? "true" : "false");

export function buildSeedSql(fixture: Fixture): string {
  const branchId = (code: string): string => {
    const branch = fixture.branches.find((b) => b.code === code);
    if (!branch) throw new Error(`Unknown branch ${code}`);
    return branch.id;
  };
  const dayId = (code: string, date: string): string => {
    const day = fixture.business_days.find((d) => d.branch_code === code && d.business_date === date);
    if (!day) throw new Error(`No business day for ${code} ${date}`);
    return day.id;
  };

  const lines: string[] = [];
  lines.push(
    "-- GENERATED by scripts/phase2/build-seed.mjs from fixtures/synthetic/phase2.json.",
    "-- Do not edit by hand. Run `npm run seed:build` after changing the fixture file.",
    `-- ${fixture.notice}`,
    `-- Fixture version: ${fixture.version}`,
    "-- Applied only by `supabase db reset` on a LOCAL development database.",
    "",
    "insert into public.organizations (id, name) values",
    `  (${text(fixture.organization.id)}, ${text(fixture.organization.name)});`,
    "",
    "insert into public.branches (id, organization_id, code, name_en, name_ar, timezone, business_day_rollover, operates_in_app) values",
    fixture.branches
      .map(
        (b) =>
          `  (${text(b.id)}, ${text(fixture.organization.id)}, ${text(b.code)}, ${text(b.name_en)}, ${text(b.name_ar)}, ${text(b.timezone)}, ${text(b.business_day_rollover)}, ${bool(b.operates_in_app)})`,
      )
      .join(",\n") + ";",
    "",
    "insert into public.business_days (id, branch_id, business_date, status, closed_at, net_sales, order_count, card_amount, opening_cash, revision) values",
    fixture.business_days
      .map(
        (d) =>
          `  (${text(d.id)}, ${text(branchId(d.branch_code))}, ${text(d.business_date)}, ${text(d.status)}, ${text(d.closed_at)}, ${num(d.net_sales)}, ${num(d.order_count)}, ${num(d.card_amount)}, ${num(d.opening_cash)}, ${d.revision})`,
      )
      .join(",\n") + ";",
    "",
    "insert into public.cash_movements (id, business_day_id, kind, amount, occurred_at, note) values",
    fixture.cash_movements
      .map(
        (m) =>
          `  (${text(m.id)}, ${text(dayId(m.branch_code, m.business_date))}, ${text(m.kind)}, ${num(m.amount)}, ${text(m.occurred_at)}, ${text(m.note)})`,
      )
      .join(",\n") + ";",
    "",
    "insert into public.cash_counts (id, business_day_id, counted_amount, counted_at, expected_cash, variance, calc_version) values",
    fixture.cash_counts
      .map(
        (c) =>
          `  (${text(c.id)}, ${text(dayId(c.branch_code, c.business_date))}, ${num(c.counted_amount)}, ${text(c.counted_at)}, ${num(c.expected_cash)}, ${num(c.variance)}, ${text(c.calc_version)})`,
      )
      .join(",\n") + ";",
    "",
    "insert into public.comparison_figures (id, branch_id, business_date, net_sales, order_count, source, entered_at) values",
    fixture.comparison_figures
      .map(
        (f) =>
          `  (${text(f.id)}, ${text(branchId(f.branch_code))}, ${text(f.business_date)}, ${num(f.net_sales)}, ${num(f.order_count)}, ${text(f.source)}, ${text(f.entered_at)})`,
      )
      .join(",\n") + ";",
    "",
  );
  return lines.join("\n");
}
