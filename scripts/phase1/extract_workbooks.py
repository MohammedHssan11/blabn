"""Phase 1 source extraction (read-only).

Reads every workbook listed in SOURCES, records workbook- and sheet-level
coverage facts, and writes a cell cache (formula + cached value per cell) to a
scratch directory for later analysis. Original workbooks are opened read-only
and are never written.

Usage:
    python scripts/phase1/extract_workbooks.py <workspace_root> <scratch_dir>

<workspace_root> is the folder that contains the repository checkout `blabn/`
and the local-only folders (`abdo temp/`, `outputs/`).
Output:
    docs/phase1/source-inventory.json   (tracked; no cell values)
    <scratch_dir>/cells/<SOURCE_ID>.pkl (local only; cell cache)
"""
