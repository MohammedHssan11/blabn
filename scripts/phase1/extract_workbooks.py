ERR_RE = re.compile(r"^#(REF!|VALUE!|DIV/0!|N/A|NAME\?|NUM!|NULL!|SPILL!|CALC!)")
EXT_RE = re.compile(r"\[\d+\]")
VOLATILE_RE = re.compile(r"\b(TODAY|NOW|RAND|RANDBETWEEN|OFFSET|INDIRECT)\s*\(", re.I)


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def norm(v):
    if isinstance(v, (dt.datetime, dt.date, dt.time)):
        return v.isoformat()
    return v


def package_parts(path: str) -> dict:
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        ext_targets = []
        for n in names:
            if n.startswith("xl/externalLinks/_rels/"):
                xml = z.read(n).decode("utf-8", "replace")
                ext_targets += re.findall(r'Target="([^"]+)"', xml)
        core = z.read("docProps/core.xml").decode("utf-8", "replace") if "docProps/core.xml" in names else ""
    def tag(t):
        m = re.search(rf"<{t}[^>]*>([^<]*)</{t}>", core)
        return m.group(1) if m else None
    return {
        "external_link_parts": [n for n in names if n.startswith("xl/externalLinks/externalLink")],
        "external_link_targets": ext_targets,
        "has_vba": any("vbaProject" in n for n in names),
        "chartsheets": [n for n in names if n.startswith("xl/chartsheets/sheet")],
        "comment_parts": [n for n in names if re.match(r"xl/comments\d+\.xml", n)],
        "drawing_parts": len([n for n in names if re.match(r"xl/drawings/drawing\d+\.xml$", n)]),
        "doc_creator": tag("dc:creator"),
        "doc_last_modified_by": tag("cp:lastModifiedBy"),
        "doc_modified": tag("dcterms:modified"),
    }


def main(root: str, scratch: str) -> None:
    os.makedirs(os.path.join(scratch, "cells"), exist_ok=True)
    out = {"generated_at": dt.datetime.now().isoformat(timespec="seconds"), "workbooks": []}
    for sid, rel, tracked, desc in SOURCES:
        path = os.path.join(root, rel)
        print(f"[{sid}] {rel}", flush=True)
        st = os.stat(path)
        wb_f = openpyxl.load_workbook(path, data_only=False)
        wb_v = openpyxl.load_workbook(path, data_only=True)
        wb_rec = {
            "id": sid, "path": rel, "tracked_in_repo": tracked, "description": desc,
            "bytes": st.st_size, "sha256": sha256(path),
            "file_mtime": dt.datetime.fromtimestamp(st.st_mtime).isoformat(timespec="seconds"),
            **package_parts(path),
            "defined_names": [],
            "sheets": [],
        }
        try:
            for name, dn in wb_f.defined_names.items():
                wb_rec["defined_names"].append({"name": name, "value": str(dn.attr_text)[:200]})
        except Exception:  # older openpyxl API
            pass
        cells = {}
        for ws in wb_f.worksheets:
            wsv = wb_v[ws.title]
            formulas = 0
            values = 0
            errors = Counter()
            err_cells = []
            ext_ref_cells = []
            volatile_cells = []
            text_numbers = 0
            sheet_cells = {}
            for row in ws.iter_rows():
                for c in row:
                    f = c.value
                    if f is None:
                        continue
                    v = wsv[c.coordinate].value
                    is_formula = isinstance(f, str) and f.startswith("=") or c.data_type == "f"
                    if not isinstance(f, (str, int, float, bool, dt.datetime, dt.date, dt.time)):
                        f = str(getattr(f, "text", f))  # ArrayFormula etc.
                        is_formula = True
                    if is_formula:
                        formulas += 1
                        if EXT_RE.search(str(f)):
                            ext_ref_cells.append(c.coordinate)
                        if VOLATILE_RE.search(str(f)):
                            volatile_cells.append(c.coordinate)
                    else:
                        values += 1
                        if isinstance(f, str) and re.fullmatch(r"\s*-?\d+(\.\d+)?\s*", f):
                            text_numbers += 1
                    if isinstance(v, str) and ERR_RE.match(v):
                        errors[v] += 1
                        err_cells.append(c.coordinate)
                    sheet_cells[c.coordinate] = (norm(f) if is_formula else None, norm(v), c.number_format)
            cells[ws.title] = sheet_cells
            comments = [{"cell": c.coordinate, "text": c.comment.text[:300]} for row in ws.iter_rows() for c in row if c.comment]
            wb_rec["sheets"].append({
                "name": ws.title,
                "kind": "worksheet",
                "state": ws.sheet_state,
                "dimension": ws.dimensions,
                "max_row": ws.max_row, "max_col": ws.max_column,
                "value_cells": values, "formula_cells": formulas,
                "cached_errors": dict(errors), "error_cells_sample": err_cells[:40],
                "error_cell_count": len(err_cells),
                "external_ref_formula_cells": len(ext_ref_cells), "external_ref_sample": ext_ref_cells[:20],
                "volatile_formula_cells": len(volatile_cells), "volatile_sample": volatile_cells[:10],
                "numbers_stored_as_text": text_numbers,
                "merged_ranges": len(ws.merged_cells.ranges),
                "comments": comments,
            })
        for cs in getattr(wb_f, "chartsheets", []):
            wb_rec["sheets"].append({"name": cs.title, "kind": "chartsheet", "state": cs.sheet_state})
        # openpyxl does not always report sheet visibility (e.g. hidden chartsheets);
        # take the state straight from xl/workbook.xml.
        import html as _html
        with zipfile.ZipFile(path) as z:
            wbxml = z.read("xl/workbook.xml").decode("utf-8", "replace")
        states = {}
        for tag in re.findall(r"<(?:\w+:)?sheet\b[^>]*>", wbxml):
            nm = _html.unescape(re.search(r'\bname="([^"]*)"', tag).group(1))
            st = re.search(r'\bstate="(\w+)"', tag)
            states[nm] = st.group(1) if st else "visible"
        for s in wb_rec["sheets"]:
            s["state"] = states.get(s["name"], s["state"])
        with open(os.path.join(scratch, "cells", f"{sid}.pkl"), "wb") as fh:
            pickle.dump(cells, fh)
        out["workbooks"].append(wb_rec)
        print(f"   sheets={len(wb_rec['sheets'])} formulas={sum(s.get('formula_cells',0) for s in wb_rec['sheets'])}"
              f" errors={sum(s.get('error_cell_count',0) for s in wb_rec['sheets'])}", flush=True)
    dest = os.path.join(root, "blabn", "docs", "phase1", "source-inventory.json")
    with open(dest, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1)
    print("wrote", dest)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
