by = defaultdict(list)
for e in plan:
    for o in e["ops"]:
        by[o["finding"]].append((e, o))
for fid in sorted(by):
    ops = by[fid]
    L.append(f"### {fid} — {fnd[fid]['title_en']}")
    L.append("")
    L.append(f"Status: **{fnd[fid]['status']}**. {fnd[fid].get('resolution_en', '')}")
    L.append("")
    cnt2 = Counter((e["id"], status(e, o)) for e, o in ops)
    L.append("Operations: " + ", ".join(f"{k[0]} {v}" + (f" ({k[1]})" if k[1] != "applied" else "") for k, v in cnt2.items()) + ".")
    ex = [(e, o) for e, o in ops if o.get("note")][:3] or ops[:3]
    for e, o in ex:
        loc = f"{o.get('sheet', '')}!{o.get('range', '')}" if o.get("range") else ""
