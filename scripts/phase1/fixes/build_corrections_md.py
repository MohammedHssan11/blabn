"""Write docs/phase1/CORRECTIONS.md (summary) and docs/phase1/corrections-log.csv
(every operation with its before value and status) from fix-plan.json, the verification
report, the diff report and the boundary tests.
Usage (repo root): python scripts/phase1/fixes/build_corrections_md.py
"""
import csv
