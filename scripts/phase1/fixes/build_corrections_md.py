# Sheets protected in the original workbooks: operations on them are not applied without the password.
protected = {}
for e in plan:
    if e["id"] in ("SRC-10", "SRC-11"):
        wb = openpyxl.load_workbook(os.path.join(REPO, e["source"]))
        protected[e["id"]] = {ws.title for ws in wb.worksheets if ws.protection.sheet}


owner = json.load(open(os.path.join(D, "decisions", "owner-deferrals.json"), encoding="utf-8"))["items"]["ledger-protected-sheets"]
PROT_STATUS = {"pending": "pending (sheet password)", "deferred": "deferred by project owner", "applied": "applied"}[owner["status"]]


def status(e, o):
    if o.get("sheet") in protected.get(e["id"], set()):
        return PROT_STATUS
    return "applied"


def describe(o):
    if o.get("delete_sheet"):
        return f"delete sheet {o['delete_sheet']}"
    if o.get("rename_sheet"):
        return f"rename sheet {o['rename_sheet']} → {o['to']}"
    if o.get("copy_sheet"):
        return f"copy sheet {o['copy_sheet']} as {o['to']}"
    if o.get("break_links"):
        return "break external links"
    for k in ("formula", "value", "date"):
        if k in o:
            return f"{k} {o[k]}"
    if o.get("replace"):
        return f"replace '{o['replace']}' with '{o['to']}'"
    if o.get("clear"):
        return "clear"
    return f"number format {o.get('numfmt')}"


rows, cnt = [], Counter()
for e in plan:
    for o in e["ops"]:
        st = status(e, o)
        cnt[st] += 1
        rows.append([e["id"], e["output"], o["finding"], o.get("sheet", ""), o.get("range", ""), str(o.get("before", ""))[:120],
                     describe(o)[:200] + (f" ({o['numfmt']})" if o.get("numfmt") and ("date" in o) else ""), o.get("note", ""), st])
with open(os.path.join(D, "corrections-log.csv"), "w", encoding="utf-8-sig", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["source_id", "corrected_file", "finding", "sheet", "range", "before", "change", "note", "status"])
    w.writerows(rows)

