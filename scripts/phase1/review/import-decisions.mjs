// Imports a decisions file that Abdo downloaded from the review page
// ("تنزيل ملف الردود") into the repository record, then regenerates the summary.
//
//   node scripts/phase1/review/import-decisions.mjs <path-to-abdo-decisions-*.json>
//   node scripts/phase1/review/import-decisions.mjs            # only regenerate the summary
//   DECISIONS_DIR=<folder> node ...                              # tests / another record
//   DECISIONS_DIR=<scratch> node ... <abdo-TRIAL-decisions-*.json> --trial   # check a trial file (never the real record)
//
// Abdo can answer every finding. Writes docs/phase1/decisions/abdo-decisions.json (merged,
// newest answer wins, older answers kept in history), DECISIONS_SUMMARY.md and abdo-decisions.csv.
// It never invents an answer: findings without an answer stay "pending".
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadRules, validateDecision, merge, isAnswered } from "./decision-rules.mjs";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const decDir = process.env.DECISIONS_DIR || join(repo, "docs", "phase1", "decisions");
const decFile = join(decDir, "abdo-decisions.json");
const rules = loadRules(repo);
const findings = rules.findings;
const all = findings.findings;
const required = all.filter((f) => f.abdo === "required");
const later = all.filter((f) => f.abdo === "later");
const LABEL = { accept: "Accept proposed change", alternative: "Propose alternative", keep: "Keep current behavior", unsure: "Not sure (unresolved)" };
const LABEL_AR = { accept: "أوافق على المقترح", alternative: "أقترح تعديلًا آخر", keep: "نُبقي الوضع الحالي", unsure: "مش متأكد / محتاج أراجع" };
const optLabel = (id, d) => {
  const q = rules.questions.get(id);
  const o = q && d.option ? q.options.find((x) => x.key === d.option) : null;
  return o ? o.en : "";
};

mkdirSync(decDir, { recursive: true });
const current = existsSync(decFile) ? JSON.parse(readFileSync(decFile, "utf8")) : { decisions: {} };
let decisions = current.decisions || {};
const arg = process.argv.slice(2).find((a) => !a.startsWith("--"));
if (arg) {
  const incoming = JSON.parse(readFileSync(arg, "utf8"));
  if (!incoming || typeof incoming.decisions !== "object") throw new Error("Not a decisions file (no 'decisions' object).");
  // Files from the trial page never enter the real record; check them with --trial into a scratch DECISIONS_DIR.
  if (incoming.trial && !process.argv.includes("--trial")) throw new Error("This is a TRIAL answers file (from abdo-review-trial.html). It is not imported into the decision record. To check it, run with --trial and DECISIONS_DIR=<scratch folder>.");
  if (process.argv.includes("--trial") && !process.env.DECISIONS_DIR) throw new Error("--trial needs DECISIONS_DIR=<scratch folder> so the real record is not touched.");
  if (!incoming.trial && process.argv.includes("--trial")) throw new Error("--trial was given but the file is not a trial file.");
  const problems = [];
  const clean = {};
  for (const [id, d] of Object.entries(incoming.decisions)) {
    try { clean[id] = validateDecision(id, d, rules); } catch (e) { problems.push(e.message); }
  }
  if (problems.length) { console.error("Rejected entries:\n  " + problems.join("\n  ")); process.exitCode = 1; }
  if (incoming.questions_version && incoming.questions_version !== rules.qfile.questions_version)
    console.warn(`Note: answers were given on questions version ${incoming.questions_version}; current is ${rules.qfile.questions_version}.`);
  decisions = merge(decisions, clean);
  console.log(`Imported ${Object.keys(clean).length} answers from ${arg}`);
}

const state = { schema: "blabn-phase1-decisions/1", reviewer: "Abdo", findings_version: findings.version, questions_version: rules.qfile.questions_version,
  updated_at: arg ? new Date().toISOString() : current.updated_at || null, decisions };
writeFileSync(decFile, JSON.stringify(state, null, 1) + "\n", "utf8");

const done = (list) => list.filter((f) => isAnswered(decisions[f.id]));
const unsure = all.filter((f) => decisions[f.id] && !isAnswered(decisions[f.id]));
const optOf = (id, d) => { const q = rules.questions.get(id); return q && d && d.option ? q.options.find((x) => x.key === d.option) : null; };
// An alternative still needs an agreed final rule unless the option itself is fully specified.
const needsRule = (id, d) => d.choice === "alternative" && (!optOf(id, d) || optOf(id, d).needs_agreement !== false);
const objections = all.filter((f) => decisions[f.id] && isAnswered(decisions[f.id]) && f.abdo !== "required" && decisions[f.id].choice !== "accept");
const cell = (s) => String(s || "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const md = [];
md.push("# Abdo's Phase 1 decisions");
md.push("");
md.push(`Generated by \`scripts/phase1/review/import-decisions.mjs\` from [abdo-decisions.json](abdo-decisions.json). Findings version \`${findings.version}\`, questions version \`${rules.qfile.questions_version}\`.`);
md.push("");
md.push(`Abdo's review page shows only the ${required.length} required questions. **Required to close Phase 1:** ${done(required).length} of ${required.length} answered` +
  (done(required).length === required.length ? " ✓" : ` — awaiting Abdo's decisions on ${required.length - done(required).length}`) +
  `. "Not sure / needs review" answers count as unresolved${unsure.length ? ` (now: ${unsure.map((f) => f.id).join(", ")})` : ""}. Later-phase questions answered: ${done(later).length} of ${later.length}.`);
md.push("");
const rule = all.filter((f) => decisions[f.id] && isAnswered(decisions[f.id]) && needsRule(f.id, decisions[f.id]));
if (rule.length) {
  md.push(`**Answers that need an agreed final rule (record with \`scripts/phase1/record_outcome.py agree\`): ${rule.map((f) => f.id).join(", ")}.**`);
  md.push("");
}
if (objections.length) {
  md.push(`**Abdo did not accept the team's handling of ${objections.length} other finding(s): ${objections.map((f) => f.id).join(", ")}.**`);
  md.push("");
}
md.push("| Q | ID | Needs Abdo | Finding | Answer | Meaning | Extra answers | Abdo's text | Saved | Earlier answers |");
md.push("|---|---|---|---|---|---|---|---|---|---|");
const rows = all.filter((f) => rules.questions.has(f.id) || decisions[f.id]);
rows.sort((a, b) => (rules.questions.get(a.id)?.n ?? 99) - (rules.questions.get(b.id)?.n ?? 99) || (a.id < b.id ? -1 : 1));
for (const f of rows) {
  const d = decisions[f.id];
  const q0 = rules.questions.get(f.id);
  const need = f.abdo === "required" ? "**Required**" : f.abdo === "later" ? `Before ${f.abdo_by}` : "";
  const extras = d && d.extras ? Object.entries(d.extras).map(([k, v]) => `${k}=${v}`).join(", ") : "";
  md.push(`| ${q0 && q0.n ? q0.n : (q0 ? "retired" : "")} | ${f.id} | ${need} | ${cell(f.title_en)} | ${d ? LABEL[d.choice] : "Pending"} | ${d ? cell(optLabel(f.id, d)) : ""} | ${extras} | ${d ? cell(d.comment) : ""} | ${d ? d.saved_at : ""} | ${d ? (d.history || []).length : ""} |`);
}
md.push("");
writeFileSync(join(decDir, "DECISIONS_SUMMARY.md"), md.join("\n"), "utf8");

const qq = (s) => `"${String(s ?? "").replace(/"/g, '""')}"`;
const csv = [["question_no", "id", "needs_abdo", "status", "title_ar", "title_en", "decision", "decision_ar", "option", "meaning", "extra_answers", "comment", "saved_at", "earlier_answers"].map(qq).join(",")];
for (const f of rows) {
  const d = decisions[f.id];
  const q0 = rules.questions.get(f.id);
  csv.push([q0 && q0.n ? q0.n : (q0 ? "retired" : ""), f.id, f.abdo || "", f.status, f.title_ar, f.title_en, d ? d.choice : "pending", d ? LABEL_AR[d.choice] : "بانتظار الرد", d?.option, d ? optLabel(f.id, d) : "", d?.extras ? JSON.stringify(d.extras) : "", d?.comment, d?.saved_at, d ? (d.history || []).length : 0].map(qq).join(","));
}
writeFileSync(join(decDir, "abdo-decisions.csv"), "﻿" + csv.join("\r\n") + "\r\n", "utf8");
console.log(`required ${done(required).length}/${required.length}, later ${done(later).length}/${later.length}, unsure ${unsure.length}, all answered ${done(all).length}/${all.length} -> ${decDir}`);
