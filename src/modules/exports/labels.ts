export type LabelKey = keyof typeof LABELS;
export type WorkbookLocale = "ar" | "en";

export function label(key: LabelKey, locale: WorkbookLocale, params?: Record<string, string | number>): string {
  const template: string = LABELS[key][locale];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}
